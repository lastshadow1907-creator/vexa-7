-- Only repair autogenerated 'vexa' handles when a valid explicit signup username exists.
-- Keep original tag numbers, premium-customized handles and founder accounts unchanged.
create or replace function public.vexa131_identity_username()
returns trigger language plpgsql security definer set search_path = '' as $$
declare wanted text;
begin
 if new.handle <> 'vexa' then return new; end if;
 if exists(select 1 from public.vexa_founders f where f.user_id=new.user_id) then return new; end if;
 select lower(trim(u.raw_user_meta_data->>'username')) into wanted from auth.users u where u.id=new.user_id;
 if wanted ~ '^[a-z0-9_]{3,20}$' and wanted <> 'vexa'
 and not exists(select 1 from public.vexa91_identity i where lower(i.handle)=wanted and i.user_id<>new.user_id)
 then new.handle:=wanted; end if;
 return new;
end $$;
revoke all on function public.vexa131_identity_username() from public, anon, authenticated;
drop trigger if exists vexa131_identity_username on public.vexa91_identity;
create trigger vexa131_identity_username before insert on public.vexa91_identity
for each row execute function public.vexa131_identity_username();
-- Backfill only unambiguous names; don't change existing custom usernames.
with candidates as (
 select i.user_id,lower(trim(u.raw_user_meta_data->>'username')) as wanted
 from public.vexa91_identity i join auth.users u on u.id=i.user_id
 where i.handle='vexa' and not exists(select 1 from public.vexa_founders f where f.user_id=i.user_id)
), valid as (
 select user_id,wanted,count(*) over(partition by wanted) as n
 from candidates where wanted ~ '^[a-z0-9_]{3,20}$' and wanted<>'vexa'
)
update public.vexa91_identity i set handle=v.wanted from valid v
where i.user_id=v.user_id and i.handle='vexa' and v.n=1
and not exists(select 1 from public.vexa91_identity x where lower(x.handle)=v.wanted and x.user_id<>i.user_id);
commit;
